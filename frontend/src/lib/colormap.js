/**
 * Map a normalized value [0,1] to an RGB array.
 */
export function infernoColor(t) {
  const idx = Math.max(0, Math.min(255, Math.round(t * 255)));
  return INFERNO[idx] || [0, 0, 0];
}

/**
 * Render a pressure map (Float64Array) onto a canvas ImageData.
 * @param {Float64Array} map - 64x64 pressure values
 * @param {number} maxVal - max value for normalization (0 = auto)
 * @returns {ImageData} - ready for ctx.putImageData
 */
export function pressureMapToImageData(map, size = 64, maxVal = 0) {
  if (maxVal <= 0) {
    maxVal = 0;
    for (let i = 0; i < map.length; i++) {
      if (map[i] > maxVal) maxVal = map[i];
    }
  }
  if (maxVal <= 0) maxVal = 1;

  const imageData = new ImageData(size, size);
  const data = imageData.data;

  for (let row = 0; row < size; row++) {
    // Flip Y so origin is bottom-left (like matplotlib)
    const srcRow = size - 1 - row;
    for (let col = 0; col < size; col++) {
      const val = map[srcRow * size + col];
      const t = Math.max(0, Math.min(1, val / maxVal));
      const [r, g, b] = infernoColor(t);
      const idx = (row * size + col) * 4;
      data[idx] = r;
      data[idx + 1] = g;
      data[idx + 2] = b;
      data[idx + 3] = 255;
    }
  }

  return imageData;
}
